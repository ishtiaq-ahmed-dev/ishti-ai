def by_id(case_id):
    return next((c for c in CASES if c["id"] == case_id), None)


def select(ids=None, cats=None, skip=None):
    out = CASES
    if ids:
        wanted = {int(x) for x in ids}
        out = [c for c in out if c["id"] in wanted]
    if cats:
        out = [c for c in out if c["cat"] in cats]
    if skip:
        skipped = {int(x) for x in skip}
        out = [c for c in out if c["id"] not in skipped]
    return out
