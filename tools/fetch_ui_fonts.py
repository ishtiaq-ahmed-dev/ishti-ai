"""Fetch the HUD's web fonts once and store them locally (Cycle 4: fast loading, local-first).

    venv\\Scripts\\python -m tools.fetch_ui_fonts

The React app used to load its fonts from fonts.googleapis.com on every start: two extra external
origins, DNS/TLS round-trips and a render-blocking stylesheet - and no fonts at all when offline.
This tool downloads the same families/weights (latin + latin-ext subsets, woff2) from Google once,
writes them to interface/app/public/fonts/ (Vite copies public/ into dist/ on build) and generates
fonts.css with the URLs rewritten to /fonts/... (served by the FastAPI server with a 1-year cache).

Filenames carry the Google version segment (e.g. inter-400-v20.woff2), so an upgrade produces new
names and the immutable cache in server.py can never serve a stale glyph set.
"""
import os
import re
import sys

import requests

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBLIC = os.path.join(ROOT, "interface", "app", "public", "fonts")
DIST = os.path.join(ROOT, "interface", "app", "dist", "fonts")

# The exact families/weights index.html asks for (keep in sync with the two index.html files).
CSS_URL = ("https://fonts.googleapis.com/css2?family=Inter:wght@300;400;500;600;700"
           "&family=JetBrains+Mono:ital,wght@0,400;0,500;0,600;1,400"
           "&family=Plus+Jakarta+Sans:wght@300;400;500;600;700;800&display=swap".replace("&", "&"))
UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) "
      "Chrome/120.0.0.0 Safari/537.36")  # a modern UA makes Google serve woff2
SUBSETS = ("latin", "latin-ext")  # everything else (cyrillic, greek, vietnamese...) is dead weight here

BLOCK = re.compile(r"/\*\s*(?P<subset>[\w-]+)\s*\*/\s*@font-face\s*\{(?P<body>[^}]+)\}")
FACE = re.compile(r"font-family:\s*'(?P<family>[^']+)';\s*font-style:\s*(?P<style>\w+);\s*"
                  r"font-weight:\s*(?P<weight>\d+);(?:[^}]*?)src:\s*url\((?P<url>[^)]+)\)")
RANGE = re.compile(r"unicode-range:\s*(?P<range>[^;]+);")


def slug(family: str) -> str:
    return family.lower().replace(" ", "-")


def main():
    css = requests.get(CSS_URL, headers={"User-Agent": UA}, timeout=30).text
    os.makedirs(PUBLIC, exist_ok=True)
    os.makedirs(DIST, exist_ok=True)

    out, seen = [], set()
    for block in BLOCK.finditer(css):
        if block.group("subset") not in SUBSETS:
            continue
        face = FACE.search(block.group("body"))
        if not face:
            continue
        family, style, weight, url = face.group("family"), face.group("style"), face.group("weight"), face.group("url")
        version = re.search(r"/v(\d+)/", url)
        name = f"{slug(family)}-{weight}{'-italic' if style == 'italic' else ''}-v{version.group(1) if version else '1'}.woff2"
        data = requests.get(url, headers={"User-Agent": UA}, timeout=60).content
        for d in (PUBLIC, DIST):
            with open(os.path.join(d, name), "wb") as f:
                f.write(data)
        rng = RANGE.search(block.group("body"))
        seen.add(name)
        out.append(f"@font-face {{\n  font-family: '{family}';\n  font-style: {style};\n  font-weight: {weight};\n"
                   f"  font-display: swap;\n  src: url('/fonts/{name}') format('woff2');\n"
                   + (f"  unicode-range: {rng.group('range')};\n" if rng else "") + "}")

    with open(os.path.join(PUBLIC, "fonts.css"), "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/fetch_ui_fonts.py - local copies of the UI web fonts. */\n\n"
                + "\n\n".join(out) + "\n")
    with open(os.path.join(DIST, "fonts.css"), "w", encoding="utf-8") as f:
        f.write(open(os.path.join(PUBLIC, "fonts.css"), encoding="utf-8").read())

    total = sum(os.path.getsize(os.path.join(PUBLIC, n)) for n in seen)
    print(f"[fonts] {len(seen)} faces, {total // 1024} KiB -> {PUBLIC}")
    for n in sorted(seen):
        print(f"  {n:44s} {os.path.getsize(os.path.join(PUBLIC, n)) // 1024:4d} KiB")


if __name__ == "__main__":
    sys.exit(main())
